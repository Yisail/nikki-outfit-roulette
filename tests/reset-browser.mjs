import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(process.env.NIKKI_TEST_RUNTIME + '/package.json');
const { chromium } = require('playwright');
const browser = await chromium.launch({ executablePath: process.env.NIKKI_TEST_BROWSER, headless: true });
const context = await browser.newContext({ viewport: { width: 320, height: 760 } });
const page = await context.newPage();
const key = 'nikki-outfit-roulette:v1';
const baseURL = process.env.NIKKI_TEST_URL ?? 'http://127.0.0.1:5173';
const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
const home = () => page.getByRole('heading', { name: '暖暖换装轮盘' }).waitFor();
const enter = async name => {
  await page.getByRole('button', { name: new RegExp(`^${name}|${name}.*›`) }).first().click();
  await page.getByRole('heading', { name, exact: true }).waitFor();
};
const draw = async () => {
  await page.getByRole('button', { name: /摇一摇|再摇一次/ }).click();
  await page.waitForFunction(() => !document.querySelector('.primary')?.disabled);
};
const confirm = async () => { await page.getByRole('button', { name: '使用这个结果' }).click(); await home(); };
const back = async () => { await page.getByRole('button', { name: '返回', exact: true }).click(); await home(); };
try {
  await page.goto(baseURL); await home();
  await enter('场景'); await draw(); await confirm();
  const scene = (await read()).draftSelection.scene;
  await enter('游戏标签'); await draw(); await confirm();
  assert.equal((await read()).draftSelection['game-tag'].length, 1);
  assert.deepEqual((await read()).draftSelection.scene, scene);
  await page.getByRole('button', { name: '重置游戏标签', exact: true }).click();
  assert.equal((await read()).draftSelection['game-tag'], undefined);
  await enter('风格'); await draw(); await confirm();
  await enter('风格'); await page.getByRole('button', { name: '双风格', exact: true }).click(); await draw(); await confirm();
  assert.equal(Object.keys((await read()).modeSelections.style).length, 2);
  await page.screenshot({ path: 'tests/release-home-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '重置风格', exact: true }).click();
  assert.deepEqual((await read()).draftSelection.scene, scene);
  assert.equal((await read()).draftSelection.style, undefined);
  assert.equal((await read()).modeSelections.style, undefined);
  await enter('风格');
  assert.ok(await page.getByRole('button', { name: '使用这个结果' }).isDisabled());
  await page.getByRole('button', { name: '单风格', exact: true }).click();
  assert.ok(await page.getByRole('button', { name: '使用这个结果' }).isDisabled());
  await draw(); await confirm();
  await enter('风格'); await page.getByRole('button', { name: '双风格', exact: true }).click(); await draw(); await confirm();
  await enter('风格');
  await page.getByRole('button', { name: '重置', exact: true }).click();
  await page.screenshot({ path: 'tests/release-reset-mobile.png', fullPage: true });
  assert.ok(await page.getByRole('button', { name: '使用这个结果' }).isDisabled());
  await page.getByRole('button', { name: '单风格', exact: true }).click();
  assert.ok(await page.getByRole('button', { name: '使用这个结果' }).isDisabled());
  await page.reload(); await page.getByRole('heading', { name: '风格', exact: true }).waitFor();
  assert.ok(await page.getByRole('button', { name: '使用这个结果' }).isDisabled());
  await draw(); await confirm();
  await enter('颜色');
  await page.getByRole('button', { name: '双色', exact: true }).click();
  await page.getByRole('button', { name: '摇一摇', exact: false }).click();
  await page.getByRole('button', { name: '重置', exact: true }).click();
  await page.waitForTimeout(1800);
  assert.ok(await page.getByRole('button', { name: '使用这个结果' }).isDisabled());
  assert.deepEqual(await page.locator('.reel-item span').allTextContents(), ['？', '？']);
  await draw(); await confirm();
  await enter('颜色');
  await page.getByRole('button', { name: '单色', exact: true }).click();
  await back();
  await enter('颜色');
  assert.equal(await page.locator('.reel-window').count(), 1);
  assert.ok(await page.getByRole('button', { name: '使用这个结果' }).isDisabled());
  assert.equal((await read()).draftSelection.color.length, 2);
  await page.getByRole('button', { name: '重置', exact: true }).click();
  assert.equal((await read()).draftSelection.color, undefined);
  await draw(); await confirm();
  await page.getByRole('button', { name: '全部重置', exact: true }).click();
  assert.equal(await read(), null);
  await page.reload(); await home();
  assert.equal(await page.locator('.unselected').count(), 4);
  assert.ok(await page.getByRole('button', { name: '完成搭配' }).isDisabled());
  await enter('场景'); await draw(); await confirm();
  const reopened = await context.newPage();
  await reopened.goto(baseURL);
  await reopened.getByRole('button', { name: '重置场景', exact: true }).waitFor();
  await reopened.close();
  await page.getByRole('button', { name: '完成搭配' }).click();
  await page.getByRole('heading', { name: '今日搭配挑战' }).waitFor();
  await page.goBack(); await home();
  assert.equal(await read(), null);
  await page.goForward(); await home();
  assert.equal(await page.getByRole('heading', { name: '今日搭配挑战' }).count(), 0);
  console.log('Reset lifecycle passed: home single/all reset, both style modes, in-page/in-animation reset, cache reopening, browser back/forward.');
} finally { await browser.close(); }
